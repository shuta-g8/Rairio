import { readFile, writeFile } from 'node:fs/promises';
import { resolve } from 'node:path';
import { fileURLToPath } from 'node:url';
import { format } from 'prettier';
import { STATIONS, RAILWAY_CATALOG } from '../shared/stations.ts';

export function stationDirectory(stations, railways) {
  return {
    stations: stations.map(
      ({
        id,
        name,
        english,
        area,
        reading,
        aliases,
        secondaryName,
        availableRailways,
        memberships,
      }) => ({
        id,
        name,
        english,
        area,
        reading,
        ...(aliases?.length ? { aliases } : {}),
        ...(secondaryName ? { secondaryName } : {}),
        availableRailways,
        memberships: memberships.map(({ railwayId, code }) => ({ railwayId, code })),
      }),
    ),
    railways: railways.map(({ id, name, code, color, stationIds }) => ({
      id,
      name,
      code,
      color,
      stationIds: [...new Set(stationIds)],
    })),
  };
}

export async function generateStationDirectory({
  stations = STATIONS,
  railways = RAILWAY_CATALOG,
  check = false,
} = {}) {
  const directory = stationDirectory(stations, railways);
  const path = new URL('../src/generated/station-directory.ts', import.meta.url);
  const formatting = JSON.parse(
    await readFile(new URL('../.prettierrc.json', import.meta.url), 'utf8'),
  );
  const source = await format(
    `// Generated by npm run data:directory. Do not edit by hand.\n` +
      `import type { DirectoryStation } from '../../shared/station-directory.ts';\n` +
      `export const STATIONS: DirectoryStation[] = ${JSON.stringify(directory.stations)};\n` +
      `export const RAILWAY_CATALOG = ${JSON.stringify(directory.railways)};\n`,
    { ...formatting, parser: 'typescript' },
  );
  const current = await readFile(path, 'utf8').catch(() => '');
  if (current === source) return;
  if (check) throw new Error('Station directory is stale. Run npm run data:directory.');
  await writeFile(path, source);
}

if (process.argv[1] && resolve(process.argv[1]) === fileURLToPath(import.meta.url)) {
  await generateStationDirectory({ check: process.argv.includes('--check') });
}
