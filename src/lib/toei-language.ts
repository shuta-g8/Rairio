export function toeiStationName(name: string, language: 'zh-Hans' | 'ko') {
  return STATION_NAMES[name]?.[language === 'zh-Hans' ? 0 : 1];
}

export function toeiStationReading(name: string) {
  return STATION_NAMES[name]?.[2];
}
